// 规则匹配：action 相同 + rule.args 中每个字段精确相等
function matches(effect, rule) {
  if (!effect || effect.action !== rule.action) return false;
  for (const [k, v] of Object.entries(rule.args || {})) {
    if (!effect.args || effect.args[k] !== v) return false;
  }
  return true;
}

